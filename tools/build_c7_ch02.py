def mm():
    segs = []
    xs = [0, 0.5, 1, 1.5, 2, 3, 4, 5, 6, 8, 10, 12, 14, 16, 18, 20]
    f = lambda s: 10 * s / (2 + s)
    for a, b in zip(xs, xs[1:]):
        c1 = (f(b) - f(a)) / (b - a)
        seg = line(round(f(a) - c1 * a, 4), round(c1, 4), a, b)
        seg["color"] = "#1D3FA8"
        segs.append(seg)
    segs.append({"kind": "poly", "coef": [10], "from": 0, "to": 20, "color": "#94A3B8"})
    return segs


