def decay_curve():
    segs = []
    xs = [i * 0.25 for i in range(17)]
    for a, b in zip(xs, xs[1:]):
        ya, yb = 100 * 0.5 ** a, 100 * 0.5 ** b
        c1 = (yb - ya) / (b - a)
        c0 = ya - c1 * a
        seg = line(round(c0, 4), round(c1, 4), a, b); seg["color"] = "#1D3FA8"; segs.append(seg)
    return segs


