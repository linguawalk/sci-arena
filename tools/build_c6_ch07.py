def decay():
    segs = []
    xs = [i * 2.5 for i in range(17)]
    for a, b in zip(xs, xs[1:]):
        ya, yb = 0.5 ** (a / 10), 0.5 ** (b / 10)
        c1 = (yb - ya) / (b - a)
        seg = line(round(ya - c1 * a, 5), round(c1, 5), a, b)
        seg["color"] = "#1D3FA8"
        segs.append(seg)
    return segs


